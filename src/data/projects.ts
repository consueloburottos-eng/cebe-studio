// Hidden modules stay in `baseProjects` (source intact, easy to bring back)
// but are excluded here — every listing, filter, "more projects" pick, and
// the sitemap/static-params all read `projects`, so this one filter is
// enough to keep them out everywhere at once.
export const projects: Project[] = baseProjects.filter((p) => !p.hidden);

export function getProject(slug: string): Project | undefined {
  return projects.find((p) => p.slug === slug);
}

export const featuredProjectSlug = "talent-capital";

export const categories: string[] = Array.from(
  new Set(projects.map((p) => p.category))
);

export function searchProjects(query: string): Project[] {
  const q = query.trim().toLowerCase();
  if (!q) return projects;
  const words = q.split(/\s+/).filter((w) => w.length > 2);
  if (!words.length) return projects;
  const scored = projects.map((p) => {
    const haystack = [
      p.title,
      p.category,
      p.tag,
      p.client,
      p.services ?? "",
      ...p.skills,
    ]
      .join(" ")
      .toLowerCase();
    const score = words.reduce((n, w) => n + (haystack.includes(w) ? 1 : 0), 0);
    return { p, score };
  });
  const matched = scored
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((x) => x.p);
  return matched.length ? matched : projects;
}
